const dataBlocks = rawData.split(/\d+\.\s+[A-Z][a-z]+/g).slice(1);
const emotionLabels = [...rawData.matchAll(/\d+\.\s+([A-Z][a-z]+)/g)].map(m => m[1]);

const parsedEmotions = dataBlocks.map((block, index) => {
    const label = emotionLabels[index];
    const meaningMatch = block.match(/Meaning:\s*(.*?)\nExample Scenarios:/s);
    const examplesMatch = block.match(/Example Scenarios:\s*(.*?)\nPhysical Signs:/s);
    const physicalSignsMatch = block.match(/Physical Signs:\s*(.*?)\nOther Attributes:/s);
    const otherMatch = block.match(/Other Attributes:\s*(.*)/s);

    return {
        label,
        definition: meaningMatch ? meaningMatch[1].trim() : "",
        example: examplesMatch ? examplesMatch[1].trim().split("\n").join(" | ") : "",
        bodySignals: physicalSignsMatch ? physicalSignsMatch[1].trim().split("\n") : [],
        otherAttributes: otherMatch ? otherMatch[1].trim().split("\n").join(" | ") : ""
    }
});

let emotionsFile = fs.readFileSync('./src/data/emotions.ts', 'utf8');

let modifiedFileContent = emotionsFile;
for (const p of parsedEmotions) {
    const regex = new RegExp(`({\\s*"id": "[^"]+",\\s*"label": "${p.label}".*?})`, 's');
    const match = modifiedFileContent.match(regex);
    if (match) {
        let objectString = match[1];

        // Remove existing definitions if any
        objectString = objectString.replace(/,\s*"definition":\s*"[^"]*"/g, "");
        objectString = objectString.replace(/,\s*"example":\s*"[^"]*"/g, "");
        objectString = objectString.replace(/,\s*"bodySignals":\s*\[[^\]]*\]/g, "");
        objectString = objectString.replace(/,\s*"otherAttributes":\s*"[^"]*"/g, ""); // if present

        // Let's just insert these properties before the closing brace
        const insertLine = `,\n        "definition": ${JSON.stringify(p.definition)},\n        "example": ${JSON.stringify(p.example)},\n        "bodySignals": ${JSON.stringify(p.bodySignals)},\n        "otherAttributes": ${JSON.stringify(p.otherAttributes)}`;
        const newObjectString = objectString.slice(0, -1) + insertLine + "\n    }";

        modifiedFileContent = modifiedFileContent.replace(objectString, newObjectString);
    } else {
        console.warn('Could not find ' + p.label);
    }
}

fs.writeFileSync('./src/data/emotions.ts', modifiedFileContent);
